#!/usr/bin/env node
// Renders backend/supabase/.env from self-hosted Infisical (Security Phase
// 5), replacing the old "cp .env.example .env, hand-fill every value"
// workflow. Requires the `infisical` CLI (https://infisical.com/docs/cli)
// on PATH and a machine identity (Universal Auth) already created for this
// project in the Infisical instance stood up via backend/infisical/ — see
// that directory's docker-compose.yml for how to stand it up, and
// docs/DEPLOYMENT.md "Secrets Management (Infisical)" for the one-time
// setup (creating the project, importing secrets, creating the identity).
//
// Usage:
//   INFISICAL_DOMAIN=http://localhost:8060/api \
//   INFISICAL_CLIENT_ID=... \
//   INFISICAL_CLIENT_SECRET=... \
//   INFISICAL_PROJECT_ID=... \
//   INFISICAL_ENV=prod \
//     node scripts/render-secrets-from-infisical.mjs
//
// Then, as before: cd backend/supabase && docker compose up -d --build.
//
// This never prints a secret value — only the CLI's own progress output
// (suppressed via --silent where the CLI supports it) and this script's
// own status lines reach stdout.

import { spawnSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const OUT_PATH = join(dirname(fileURLToPath(import.meta.url)), '..', 'supabase', '.env')

function requireEnv(name) {
  const value = process.env[name]
  if (!value) {
    console.error(`Missing required environment variable: ${name}`)
    console.error('See this script\'s own header comment for the full list.')
    process.exit(1)
  }
  return value
}

const domain = requireEnv('INFISICAL_DOMAIN')
const clientId = requireEnv('INFISICAL_CLIENT_ID')
const clientSecret = requireEnv('INFISICAL_CLIENT_SECRET')
const projectId = requireEnv('INFISICAL_PROJECT_ID')
const env = process.env.INFISICAL_ENV || 'prod'

const cliEnv = { ...process.env, INFISICAL_DOMAIN: domain }

const versionCheck = spawnSync('infisical', ['--version'], { stdio: 'ignore' })
if (versionCheck.error) {
  console.error('The `infisical` CLI is not on PATH. Install it first: https://infisical.com/docs/cli/overview')
  process.exit(1)
}

console.log(`Authenticating to Infisical at ${domain} via Universal Auth...`)
const login = spawnSync(
  'infisical',
  ['login', '--method=universal-auth', `--client-id=${clientId}`, `--client-secret=${clientSecret}`, '--silent', '--plain'],
  { env: cliEnv, encoding: 'utf8' },
)
if (login.status !== 0) {
  console.error('infisical login failed:')
  console.error(login.stderr || login.stdout)
  process.exit(1)
}
const token = login.stdout.trim()

console.log(`Exporting secrets (project ${projectId}, environment "${env}") to backend/supabase/.env...`)
const exportResult = spawnSync(
  'infisical',
  ['export', `--projectId=${projectId}`, `--env=${env}`, '--format=dotenv'],
  { env: { ...cliEnv, INFISICAL_TOKEN: token }, encoding: 'utf8' },
)
if (exportResult.status !== 0) {
  console.error('infisical export failed:')
  console.error(exportResult.stderr || exportResult.stdout)
  process.exit(1)
}

writeFileSync(
  OUT_PATH,
  `# Generated by scripts/render-secrets-from-infisical.mjs — do not hand-edit.\n# Re-run this script after changing secrets in Infisical, then restart the affected containers.\n${exportResult.stdout}`,
)
console.log(`Wrote ${OUT_PATH}`)
console.log('Next: cd backend/supabase && docker compose up -d --build')
